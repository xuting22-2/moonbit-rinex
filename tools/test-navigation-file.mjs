import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {spawnSync} from 'node:child_process';
import {inspectNavigation,exchangeNavigationFile,evaluateNavigationRecord} from './navigation-file.mjs';

const base=process.argv[2]??os.tmpdir();
const scratch=fs.mkdtempSync(path.join(base,'navigation-contract-'));
const input='examples/navigation-core-4.02.rnx',expected=JSON.parse(fs.readFileSync('examples/navigation-core-expected.json','utf8'));
assert.equal(createHash('sha256').update(fs.readFileSync(input)).digest('hex'),expected.rnxSha256);
const directory=path.join(scratch,'exchange');
const manifest=await exchangeNavigationFile(input,directory);
assert.equal(manifest.complete,true);assert.equal(manifest.qualified,true);assert.equal(manifest.records,34);
assert.deepEqual({...manifest.counts},expected.counts);
const reopened=await inspectNavigation(path.join(directory,'navigation.rnx'));
assert.equal(reopened.records,34);assert.deepEqual({...reopened.counts},expected.counts);
const python=process.env.PYTHON??(process.platform==='win32'?'python':'python3');
const recipient=spawnSync(python,['tools/reference/verify-navigation-exchange.py',input,directory],{encoding:'utf8'});
assert.equal(recipient.status,0,recipient.stderr||recipient.stdout);
const messages=fs.readFileSync(path.join(directory,'messages.ndjson'),'utf8').trimEnd().split('\n').map(JSON.parse);
const r=await evaluateNavigationRecord(input,1,{elapsedSeconds:0});
assert.equal(r.result.x,20000000);assert.equal(r.result.frame,'PZ-90');
const e=await evaluateNavigationRecord(input,3,{elapsedSeconds:600,signal:'E5a'});
assert.equal(e.result.frame,'GTRF');assert.equal(e.source.family,'FNAV');
assert.equal(e.result.group_delays.find(f=>f.name==='bgd_e5b_e1').value,undefined);
await assert.rejects(evaluateNavigationRecord(input,3,{signal:'E1B'}),/Galileo signal/);
await assert.rejects(evaluateNavigationRecord(input,1,{elapsedSeconds:1800.1}),/EphemerisExpired/);
await assert.rejects(evaluateNavigationRecord(input,0),/invalid navigation/);
await assert.rejects(evaluateNavigationRecord(input,99999),/outside file/);
await assert.rejects(exchangeNavigationFile(input,directory),/EEXIST/);
const stoIndex=messages.findIndex(m=>m.category==='STO')+1,eopIndex=messages.findIndex(m=>m.category==='EOP')+1;
const sto=(await evaluateNavigationRecord(input,stoIndex,{elapsedSeconds:10})).result;
assert.ok(Math.abs(sto-1.0200003e-9)<1e-22);
const eop=(await evaluateNavigationRecord(input,eopIndex,{elapsedSeconds:86400})).result;
assert.ok(Math.abs(eop.xp_arcsec-.12015)<1e-14);
// Real failure inputs and unqualified parts stay in the scratch directory.
const raw=fs.readFileSync(input,'ascii');
const truncated=path.join(scratch,'truncated.rnx');fs.writeFileSync(truncated,raw.trimEnd().split('\n').slice(0,-1).join('\n')+'\n');
const failed=path.join(scratch,'failed');await assert.rejects(exchangeNavigationFile(truncated,failed),/truncated/);
assert.equal(JSON.parse(fs.readFileSync(path.join(failed,'manifest.json'),'utf8')).complete,false);
assert.equal(fs.existsSync(path.join(failed,'navigation.rnx')),false);
const future=path.join(scratch,'future.rnx');fs.writeFileSync(future,raw+'> XYZ G01 FUTR\nopaque future payload\n');
const preserved=await exchangeNavigationFile(future,path.join(scratch,'future-exchange'));
assert.equal(preserved.complete,true);assert.equal(preserved.allSupported,false);assert.equal(preserved.qualified,false);assert.equal(preserved.unsupportedRecords,1);
assert.equal(fs.readFileSync(path.join(scratch,'future-exchange','navigation.rnx'),'ascii'),raw+'> XYZ G01 FUTR\nopaque future payload\n');
const bad=path.join(scratch,'bad-source.rnx');fs.writeFileSync(bad,raw.replace('> EPH E02 INAV','> EPH E03 INAV'));
await assert.rejects(inspectNavigation(bad),/satellite mismatch/);
const crlf=path.join(scratch,'crlf-no-final-newline.rnx');fs.writeFileSync(crlf,raw.trimEnd().replaceAll('\n','\r\n'));
await exchangeNavigationFile(crlf,path.join(scratch,'crlf'));
assert.equal(fs.readFileSync(path.join(scratch,'crlf','navigation.rnx'),'ascii'),raw);
console.log(JSON.stringify({status:'navigation_host_contract_passed',records:34,scratch,independentRecipient:JSON.parse(recipient.stdout),errors:'Truncation, source mismatch, unknown preservation, bad query/age/signal, overwrite, CRLF/final-line'}));
